import type { IntakeDirectory } from 'bingo-fs';
import { z } from 'zod';

import { rootBase } from '../../bases/rootBase.ts';
import { defaults } from '../../options.ts';
import { action, createSetupSteps } from '../../utils/actions.ts';
import { parseJsonText, readText } from '../../utils/files.ts';
import { formatJson } from '../../utils/json.ts';
import { getReleaseAppCondition, getWorkflowPath } from '../../utils/options.ts';
import { pinned } from '../../utils/pins.ts';
import { formatYamlFile } from '../../utils/yaml.ts';
import { blockCSpell } from './blockCSpell.ts';
import { blockRootPackageJson } from './blockRootPackageJson.ts';

const changesetReadme = `# Changesets

Hello and welcome! This folder has been automatically generated by \`@changesets/cli\`, a build tool that works
with multi-package repos, or single-package repos to help you version and publish your code. You can
find the full documentation for it [in our repository](https://github.com/changesets/changesets)

We have a quick list of common questions to get you started engaging with this project in
[our documentation](https://github.com/changesets/changesets/blob/main/docs/common-questions.md)
`;

export const blockChangesets = rootBase.createBlock({
  about: {
    name: 'Changesets',
  },
  intake({ files, options }) {
    const existingConfig = readText(files, '.changeset/config.json');
    const existingWorkflow = readText(
      files,
      `.github/workflows/${getWorkflowPath(options, 'release')}`,
    );
    const existingReadme = readText(files, '.changeset/README.md');
    const otherReleaseTool = findOtherReleaseTool(files, existingConfig, existingWorkflow);
    const rootScripts = parseJsonText(readText(files, 'package.json')).scripts as
      | Record<string, string>
      | undefined;
    return {
      ...(rootScripts?.build !== undefined && { rootBuild: true }),
      ...(existingConfig && { existingConfig }),
      ...(otherReleaseTool && { otherReleaseTool }),
      ...(existingReadme && { existingReadme }),
      ...(existingWorkflow && { existingWorkflow }),
    };
  },
  props: {
    existingConfig: z.string().optional(),
    rootBuild: z.boolean().optional(),
    otherReleaseTool: z.string().optional(),
    existingWorkflow: z.string().optional(),
    existingReadme: z.string().optional(),
    fixed: z.array(z.array(z.string())).optional(),
  },
  produce({ options, props }) {
    if (props.otherReleaseTool) {
      return {
        suggestions: [
          `A Changesets release workflow wasn't added because this repository releases with ${props.otherReleaseTool}.`,
        ],
      };
    }

    const app = options.releaseApp ?? defaults.releaseApp;
    // Existing configs may intentionally differ, such as in privatePackages
    const config =
      props.existingConfig === undefined
        ? {
            $schema: 'https://unpkg.com/@changesets/config@4.0.0/schema.json',
            changelog: [
              '@changesets/changelog-github',
              { repo: `${options.owner}/${options.repository}` },
            ],
            commit: false,
            fixed: props.fixed ?? [],
            linked: [],
            access: 'public',
            baseBranch: 'main',
            updateInternalDependencies: 'patch',
            ignore: [],
            privatePackages: false,
          }
        : parseJsonText(props.existingConfig);

    const appToken = (permissions: Record<string, string>) => ({
      name: 'Create Token',
      id: 'create_token',
      uses: action('actions/create-github-app-token'),
      with: {
        'client-id': `\${{ vars.${app}_CLIENT_ID }}`,
        ...permissions,
        'private-key': `\${{ secrets.${app}_PRIVATE_KEY }}`,
      },
    });

    const setup = (inputs?: Record<string, unknown>) => createSetupSteps(options, inputs);

    const workflow = {
      name: 'Release',
      on: { push: { branches: ['main'] } },
      permissions: {},
      concurrency: { group: '${{ github.workflow }}-${{ github.ref }}', queue: 'max' },
      jobs: {
        select_mode: {
          name: 'Select Mode',
          if: getReleaseAppCondition(options),
          'runs-on': 'ubuntu-latest',
          permissions: { contents: 'read' },
          outputs: {
            mode: '${{ steps.select_mode.outputs.mode }}',
            'publish-plan-artifact-id': '${{ steps.select_mode.outputs.publish-plan-artifact-id }}',
          },
          steps: [
            ...setup(),
            { uses: action('changesets/action', '/select-mode'), id: 'select_mode' },
          ],
        },
        version: {
          name: 'Version',
          if: "needs.select_mode.outputs.mode == 'version'",
          needs: 'select_mode',
          'runs-on': 'ubuntu-latest',
          permissions: { contents: 'read' },
          steps: [
            ...setup(),
            appToken({ 'permission-contents': 'write', 'permission-pull-requests': 'write' }),
            {
              name: 'Version Packages',
              uses: action('changesets/action', '/version'),
              with: {
                'commit-message': 'chore: version packages',
                'github-token': '${{ steps.create_token.outputs.token }}',
                'pr-title': 'chore: version packages',
              },
            },
          ],
        },
        pack: {
          name: 'Pack',
          if: "needs.select_mode.outputs.mode == 'publish'",
          needs: 'select_mode',
          'runs-on': 'ubuntu-latest',
          permissions: { contents: 'read' },
          outputs: {
            'pack-dir-artifact-id': '${{ steps.pack.outputs.pack-dir-artifact-id }}',
          },
          steps: [
            ...setup({ cache: false }),
            ...(options.packages?.some((pkg) => pkg.scripts?.includes('prebuild'))
              ? [{ name: 'Prebuild', run: 'pnpm run -r prebuild' }]
              : []),
            ...(props.rootBuild ||
            (!options.buildPackageSkipped &&
              options.packages?.some((pkg) => pkg.kind === 'library'))
              ? [{ name: 'Build', run: 'pnpm build' }]
              : []),
            {
              name: 'Pack',
              uses: action('changesets/action', '/pack'),
              id: 'pack',
              with: {
                'publish-plan-artifact-id':
                  '${{ needs.select_mode.outputs.publish-plan-artifact-id }}',
              },
            },
          ],
        },
        publish: {
          name: 'Publish',
          needs: 'pack',
          'runs-on': 'ubuntu-latest',
          permissions: { contents: 'read', 'id-token': 'write' },
          outputs: {
            published: '${{ steps.publish.outputs.published }}',
            'published-packages': "${{ steps.publish.outputs['published-packages'] }}",
          },
          steps: [
            // No dependency cache in the one job that holds both OIDC and release tokens
            ...setup({ cache: false }),
            appToken({ 'permission-contents': 'write' }),
            {
              name: 'Publish Packages',
              id: 'publish',
              uses: action('changesets/action', '/publish'),
              with: {
                'github-token': '${{ steps.create_token.outputs.token }}',
                'pack-dir-artifact-id': '${{ needs.pack.outputs.pack-dir-artifact-id }}',
              },
            },
          ],
        },
        comment: {
          if: "needs.publish.outputs.published == 'true'",
          name: 'Comment on Released PRs and Issues',
          needs: 'publish',
          'runs-on': 'ubuntu-latest',
          permissions: { contents: 'read', issues: 'write', 'pull-requests': 'write' },
          steps: [
            {
              uses: action('actions/checkout'),
              with: { 'fetch-depth': 0, 'persist-credentials': false },
            },
            {
              uses: action('marcalexiei/changesets-release-commenter'),
              with: {
                'published-packages': "${{ needs.publish.outputs['published-packages'] }}",
              },
            },
          ],
        },
      },
    };

    return {
      extensions: [
        blockCSpell({
          words: ['marcalexiei', ...app.split('_').filter((word) => /^[A-Z]+$/.test(word))],
        }),
        blockRootPackageJson({
          // Knip would report the GitHub changelog as unused if the config doesn't use it
          devDependencies: pinned(
            ...(JSON.stringify(config.changelog ?? null).includes('@changesets/changelog-github')
              ? (['@changesets/changelog-github'] as const)
              : []),
            '@changesets/cli',
          ),
        }),
      ],
      files: {
        '.changeset': {
          'config.json': formatJson(config, props.existingConfig),
          'README.md': props.existingReadme ?? changesetReadme,
        },
        '.github': {
          workflows: {
            [getWorkflowPath(options, 'release')]: formatYamlFile(
              workflow,
              props.existingWorkflow,
              {
                name: `.github/workflows/release.${options.workflowExtension ?? 'yaml'}`,
                sorted: options.workflowKeysSorted,
                workflow: true,
              },
            ),
          },
        },
      },
    };
  },
});

function findOtherReleaseTool(
  files: IntakeDirectory,
  changesetConfig: string | undefined,
  releaseWorkflow: string | undefined,
): string | undefined {
  if (changesetConfig !== undefined && releaseWorkflow === undefined) {
    return undefined;
  }

  const manifest = parseJsonText(readText(files, 'package.json'), 'package.json');
  const dependencies = {
    ...(manifest.dependencies as object | undefined),
    ...(manifest.devDependencies as object | undefined),
  };
  const fromDependencies = ['release-it', 'semantic-release', 'release-please', 'lerna'].find(
    (name) => name in dependencies,
  );
  if (fromDependencies) {
    return fromDependencies;
  }

  const nx = parseJsonText(readText(files, 'nx.json'), 'nx.json');
  if (nx.release) {
    return 'nx release';
  }

  // Workflows without CTM's sub-actions are the repository's own
  return releaseWorkflow !== undefined && !releaseWorkflow.includes('changesets/action/select-mode')
    ? 'its own release workflow'
    : undefined;
}
